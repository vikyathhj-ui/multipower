#!/usr/bin/env python3
"""Regenerate the README results block from results/summary.json (BRIEF Phase 5).

Rewrites everything between <!-- RESULTS:BEGIN --> and <!-- RESULTS:END --> in README.md.
Nothing in that block is typed by hand.

    python3 scripts/gen_readme_table.py           # rewrite README.md
    python3 scripts/gen_readme_table.py --check   # exit 1 if README.md is stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
README = REPO / "README.md"
BEGIN, END = "<!-- RESULTS:BEGIN -->", "<!-- RESULTS:END -->"


def us(x):
    return "never" if x is None else f"{x * 1e6:.3g} µs"


def block(s: dict) -> str:
    f, v, be = s["flow"], s["verification"]["checks"], s["breakeven"]
    t_ss = f["timing"]["max_ss_100C_1v60"]
    sim, cov, frm, mut = v["simulation"], v["coverage"], v["formal"], v["mutation"]
    soak = sim["per_test"].get("test_soak", {})
    so = f["signoff"]
    clean = all(x == 0 for x in so.values())
    lines = [
        "**PMU layout** (LibreLane, sky130A `sky130_fd_sc_hd`, always-on logic only)", "",
        "| Clock | Worst setup slack (9 corners) | Worst hold slack | fmax @ ss 100 °C 1.60 V | Cells | Cell area | Power (default activity) | DRC / LVS / antenna |",
        "|---|---|---|---|---|---|---|---|",
        f"| {f['clock_period_ns']:g} ns | {f['worst_setup_ws_ns']:+.3f} ns | {f['worst_hold_ws_ns']:+.3f} ns | "
        f"{t_ss['fmax_MHz']} MHz | {f['area']['stdcell_count']} | {f['area']['stdcell_area_um2']:.1f} µm² | "
        f"{f['power_W']['total'] * 1e3:.2f} mW | {'clean' if clean else so} |",
        "",
        "**Verification**", "",
        "| Formal (SymbiYosys) | Simulation (cocotb, Icarus) | Random soak | Functional coverage | Mutation |",
        "|---|---|---|---|---|",
        f"| k-induction ({frm['proofs']}): properties 1–8 proven, 9 as per-state time bounds; covers: {frm['covers_reached']} of "
        f"{frm['covers_total']} reached{'' if frm['covers'] == 'PASS' else ' (1 open, see Limitations)' if frm['covers_total'] - frm['covers_reached'] == 1 else ' (see Limitations)'} | {sim['tests'] - len(sim['failed'])}/{sim['tests']} tests pass, "
        f"{sim['sequences_checked']} sequences checked | {sim['soak_requests']} requests, {soak.get('errors')} errors | "
        f"{cov['percent']:g}% of {cov['bins']} bins | {mut['mutants'] - 1} bugs inserted, "
        f"{'all caught' if not mut['missed'] else 'missed: ' + ', '.join(mut['missed'])} |",
        "",
        "**Break-even residency** (representative load, assumptions in `docs/POWER_ANALYSIS.md`)", "",
        "| Corner | IDLE vs RUN | SLEEP vs RUN | SLEEP vs IDLE | SHUTDOWN vs IDLE |",
        "|---|---|---|---|---|",
    ]
    for c in be["breakeven_s"]:
        lines.append(f"| {c} | {us(be['breakeven_s'][c]['IDLE'])} | {us(be['breakeven_s'][c]['SLEEP'])} | "
                     f"{us(be['breakeven_vs_IDLE_s'][c]['SLEEP'])} | {us(be['breakeven_vs_IDLE_s'][c]['SHUTDOWN'])} |")
    lines += ["", f"Generated by `scripts/gen_readme_table.py` from `results/summary.json`; liveness bound "
              f"{s['liveness_bound']['bound_cycles']} cycles (`results/formal/liveness_bound.json`)."]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    s = json.loads((REPO / "results" / "summary.json").read_text())
    text = README.read_text()
    if BEGIN not in text or END not in text:
        print(f"README.md has no {BEGIN} / {END} markers")
        return 1
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: f"{BEGIN}\n{block(s)}\n{END}", text, flags=re.S)
    if a.check:
        if new != text:
            print("README.md results are stale: run python3 scripts/gen_readme_table.py")
            return 1
        print("README.md results are up to date")
        return 0
    README.write_text(new)
    print("README.md results regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
