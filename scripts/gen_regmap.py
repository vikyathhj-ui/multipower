#!/usr/bin/env python3
"""Generate the register-map views from scripts/regmap.yaml (single source, BRIEF A2 / Phase 1).

Outputs:
  docs/REGMAP.md   human-readable map
  sw/pmu_regs.h    C header: addresses, field shifts/masks, reset values, enums
  tb/regmap.py     Python dict for the cocotb testbench

    python3 scripts/gen_regmap.py           # write all three
    python3 scripts/gen_regmap.py --check   # exit 1 if any output is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "scripts" / "regmap.yaml"
BANNER = "Generated by scripts/gen_regmap.py from scripts/regmap.yaml. Do not edit."


def load() -> dict:
    m = yaml.safe_load(SRC.read_text())
    seen = set()
    for r in m["registers"]:
        assert r["addr"] % 4 == 0 and r["addr"] < (1 << m["addr_width"]), r["name"]
        assert r["addr"] not in seen, f"duplicate address {r['addr']:#x}"
        seen.add(r["addr"])
        used = 0
        r["reset"] = 0
        for f in r["fields"]:
            msb, lsb = f["bits"]
            assert m["data_width"] > msb >= lsb >= 0, (r["name"], f["name"])
            mask = ((1 << (msb - lsb + 1)) - 1) << lsb
            assert not used & mask, f"overlapping fields in {r['name']}"
            assert f["reset"] < (1 << (msb - lsb + 1)), (r["name"], f["name"], "reset too wide")
            used |= mask
            f["mask"] = mask
            r["reset"] |= f["reset"] << lsb
        r["mask"] = used
    return m


def bits(f: dict) -> str:
    msb, lsb = f["bits"]
    return f"[{msb}]" if msb == lsb else f"[{msb}:{lsb}]"


def markdown(m: dict) -> str:
    out = [f"# Register map", "", f"<!-- {BANNER} -->", "",
           f"APB3 completer, {m['data_width']}-bit data, `PADDR[{m['addr_width'] - 1}:0]`, word-aligned. "
           "Access types: **RO** read-only (writes return `PSLVERR`=1 and change nothing), **RW** read/write, "
           "**W1C** write 1 to clear. Unlisted bits read 0. Any address not listed below returns "
           "`PSLVERR`=1 (ARM IHI 0024E §3.4) and changes nothing.", "",
           "## Summary", "", "| Address | Name | Access | Reset | Description |", "|---|---|---|---|---|"]
    for r in m["registers"]:
        out.append(f"| `{r['addr']:#05x}` | [{r['name']}](#{r['name'].lower()}) | {r['access']} | "
                   f"`{r['reset']:#010x}` | {r['desc'].split('. ')[0].rstrip('.')}. |")
    out += ["", "## Encodings", ""]
    for en, vals in m["enums"].items():
        out.append(f"**{en}**: " + ", ".join(f"{k} = {v}" for k, v in vals.items()))
        out.append("")
    out += ["## Registers", ""]
    for r in m["registers"]:
        out += [f"### {r['name']}", "", f"`{r['addr']:#05x}`, {r['access']}, reset `{r['reset']:#010x}`. "
                f"{r['desc']}", "", "| Bits | Field | Reset | Description |", "|---|---|---|---|"]
        for f in sorted(r["fields"], key=lambda f: -f["bits"][0]):
            enum = f" ({f['enum']} encoding)" if "enum" in f else ""
            out.append(f"| {bits(f)} | {f['name']} | `{f['reset']:#x}` | {f['desc']}{enum} |")
        out.append("")
    return "\n".join(out)


def c_header(m: dict) -> str:
    P = m["device"].upper()
    out = [f"/* {BANNER} */", f"#ifndef {P}_REGS_H", f"#define {P}_REGS_H", "", "#include <stdint.h>", "",
           f"#define {P}_N_PD {m['n_pd']}u", ""]
    for i, d in enumerate(m["domains"]):
        out.append(f"#define {P}_PD_{d} {i}u")
    out.append("")
    for en, vals in m["enums"].items():
        for k, v in vals.items():
            out.append(f"#define {P}_{en.upper()}_{k} {v}u")
        out.append("")
    for r in m["registers"]:
        n = f"{P}_{r['name']}"
        out += [f"/* {r['name']} ({r['access']}): {r['desc'].split('. ')[0].rstrip('.')} */",
                f"#define {n}_OFFSET {r['addr']:#05x}u", f"#define {n}_RESET {r['reset']:#010x}u"]
        for f in r["fields"]:
            out += [f"#define {n}_{f['name']}_SHIFT {f['bits'][1]}u", f"#define {n}_{f['name']}_MASK {f['mask']:#010x}u"]
        out.append("")
    out += [f"#endif /* {P}_REGS_H */", ""]
    return "\n".join(out)


def py_dict(m: dict) -> str:
    regs = {r["name"]: {"addr": r["addr"], "access": r["access"], "reset": r["reset"], "mask": r["mask"],
                        "fields": {f["name"]: {"lsb": f["bits"][1], "msb": f["bits"][0], "mask": f["mask"],
                                               "reset": f["reset"]} for f in r["fields"]}}
            for r in m["registers"]}
    lines = [f'"""{BANNER}"""', "", f"N_PD = {m['n_pd']}", f"DOMAINS = {m['domains']!r}", ""]
    for en, vals in m["enums"].items():
        lines.append(f"{en.upper()} = {dict(vals)!r}")
    lines += ["", "REGS = {"]
    for name, r in regs.items():
        lines.append(f"    {name!r}: {r!r},")
    lines += ["}", "", "ADDR = {name: r['addr'] for name, r in REGS.items()}", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    m = load()
    outputs = {REPO / "docs" / "REGMAP.md": markdown(m) + "\n", REPO / "sw" / "pmu_regs.h": c_header(m),
               REPO / "tb" / "regmap.py": py_dict(m)}
    stale = [p for p, t in outputs.items() if not p.exists() or p.read_text() != t]
    if a.check:
        for p in stale:
            print(f"stale: {p.relative_to(REPO)} (run python3 scripts/gen_regmap.py)")
        return 1 if stale else 0
    for p, t in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t)
        print(f"-> {p.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
