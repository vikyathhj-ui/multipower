#!/usr/bin/env python3
"""Write results/resume_bullets.md: 3 resume bullets whose every number comes from results/summary.json
(BRIEF Phase 5). The sentences are templates; the script fills in the numbers.

    python3 scripts/resume_bullets.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent


def main() -> int:
    s = json.loads((REPO / "results" / "summary.json").read_text())
    v = s["verification"]["checks"]
    f, be = s["flow"], s["breakeven"]
    sim, cov, mut = v["simulation"], v["coverage"], v["mutation"]
    n_corners = len(f["timing"])
    sleep_tt = be["breakeven_vs_IDLE_s"]["TT"]["SLEEP"]
    # residency from which SHUTDOWN is the best mode, at 25 C (TT) and 100 C (FF)
    sd = {c: next(x["from_s"] for x in be["policy"][c] if x["mode"] == "SHUTDOWN") for c in ("TT", "FF")}
    b1 = (f"Designed a 3-domain SoC power-management unit in SystemVerilog (APB3 registers, Arm Q-Channel "
          f"handshakes, staged trickle/main power switches with an inrush arbiter, retention and isolation "
          f"sequencing) and closed it on SKY130 with LibreLane at {f['clock_period_ns']:g} ns across all "
          f"{n_corners} PVT corners ({f['area']['stdcell_count']} cells, DRC/LVS clean), using real sky130 "
          f"clock-gate and isolation cells.")
    b2 = (f"Proved the power-sequencing safety properties with SymbiYosys k-induction (formal found a real "
          f"stale-acknowledge bug), and built a power-aware cocotb testbench that corrupts unpowered state to X: "
          f"{sim['soak_requests']:,} random mode requests, {sim['sequences_checked']:,} sequences checked, "
          f"{cov['percent']:g}% functional coverage; all {mut['mutants'] - 1} injected bugs caught.")
    b3 = (f"Wrote IEEE 1801 UPF power intent and a break-even residency analysis from sky130 liberty leakage "
          f"and measured transition times: retention SLEEP beats clock gating after {sleep_tt * 1e6:.3g} µs, and "
          f"full shutdown becomes the best mode after {sd['TT'] * 1e3:.3g} ms at 25 °C but {sd['FF'] * 1e6:.3g} µs "
          f"at 100 °C, so the mode policy must track temperature.")
    out = REPO / "results" / "resume_bullets.md"
    out.write_text("# Resume bullets\n\nGenerated by `scripts/resume_bullets.py`; every number comes from "
                   "`results/summary.json`.\n\n" + "\n".join(f"- {b}" for b in (b1, b2, b3)) + "\n")
    print(out.read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
